import argparse
import json
import os
import pickle
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.cluster import KMeans
from sklearn.manifold import TSNE
from sklearn.metrics import (
    calinski_harabasz_score,
    davies_bouldin_score,
    silhouette_score,
)


DEFAULT_CLUSTERS = {"geolife": 8, "porto": 3}


def load_pickle(path):
    with open(path, "rb") as f:
        return pickle.load(f)


def find_file(candidates, description):
    for path in candidates:
        if path.is_file():
            return path
    searched = "\n".join(str(path) for path in candidates)
    raise FileNotFoundError(f"Could not find {description}. Searched:\n{searched}")


def load_evaluation_data(dataset, processed_root, embedding_file=None):
    dataset_dir = Path(processed_root) / dataset
    output_dir = dataset_dir / "output"

    if embedding_file:
        embeddings_path = Path(embedding_file)
    else:
        embeddings_path = find_file(
            [
                output_dir / f"trajectory_embeddings_{dataset}.npy",
                output_dir / f"predicted_embeddings_{dataset}_best.npy",
                output_dir / f"predicted_embeddings_{dataset}.npy",
            ],
            f"{dataset} trajectory embeddings",
        )

    sequence_path = find_file(
        [
            output_dir / f"traj_seq_embed_{dataset}.pkl",
            output_dir / "traj_seq_embed.pkl",
        ],
        f"{dataset} trajectory sequence embeddings",
    )
    context_embedding_path = find_file(
        [
            output_dir / f"traj_context_embeddings_{dataset}.pkl",
            output_dir / "traj_context_embeddings.pkl",
        ],
        f"{dataset} trajectory context embeddings",
    )
    day_hour_path = find_file(
        [
            output_dir / f"traj_day_hour_pairs_{dataset}.pkl",
            output_dir / "traj_day_hour_pairs.pkl",
        ],
        f"{dataset} trajectory date-hour pairs",
    )
    weekday_path = find_file(
        [
            dataset_dir / "weekday_date_indices.pkl",
            dataset_dir / "weekday_date_indices13.pkl",
            dataset_dir / "316_3M" / "weekday_date_indices.pkl",
            dataset_dir / "316_3M" / "weekday_date_indices13.pkl",
        ],
        f"{dataset} weekday-date index file",
    )

    embeddings = np.load(embeddings_path)
    sequence_embeddings = load_pickle(sequence_path)
    context_embeddings = load_pickle(context_embedding_path)
    day_hour_pairs = load_pickle(day_hour_path)
    weekday_date_indices = load_pickle(weekday_path)

    # The encoder produces outputs in sorted order of the shared trajectory IDs.
    valid_ids = sorted(set(sequence_embeddings) & set(context_embeddings))
    if len(valid_ids) != len(embeddings):
        raise ValueError(
            "Embedding/trajectory alignment mismatch: "
            f"{len(embeddings)} embeddings but {len(valid_ids)} shared trajectory IDs. "
            "Ensure embeddings were generated by the matching dataset-specific encoder run."
        )

    return {
        "dataset_dir": dataset_dir,
        "output_dir": output_dir,
        "embeddings_path": embeddings_path,
        "embeddings": embeddings,
        "valid_ids": valid_ids,
        "day_hour_pairs": day_hour_pairs,
        "weekday_date_indices": weekday_date_indices,
    }


def build_date_to_weekday(weekday_date_indices):
    date_to_weekday = {}
    for weekday, date_indices in enumerate(weekday_date_indices):
        for date_index in date_indices:
            date_to_weekday[date_index] = weekday
    return date_to_weekday


def calculate_context_purity(cluster_labels, trajectory_ids, day_hour_pairs,
                             weekday_date_indices, min_cluster_size=1):
    date_to_weekday = build_date_to_weekday(weekday_date_indices)
    purity_scores = {}
    dominant_contexts = {}

    for cluster_id in np.unique(cluster_labels):
        cluster_positions = np.flatnonzero(cluster_labels == cluster_id)
        if len(cluster_positions) < min_cluster_size:
            continue

        context_counts = Counter()
        for position in cluster_positions:
            trajectory_id = trajectory_ids[position]
            for date_index, hour in day_hour_pairs.get(trajectory_id, []):
                weekday = date_to_weekday.get(date_index)
                if weekday is not None:
                    context_counts[(int(weekday), int(hour))] += 1

        if not context_counts:
            purity_scores[int(cluster_id)] = 0.0
            dominant_contexts[int(cluster_id)] = (None, 0)
            continue

        dominant_context, dominant_count = context_counts.most_common(1)[0]
        total_occurrences = sum(context_counts.values())
        purity_scores[int(cluster_id)] = dominant_count / total_occurrences
        dominant_contexts[int(cluster_id)] = (
            dominant_context,
            dominant_count,
        )

    mean_purity = (
        float(np.mean(list(purity_scores.values())))
        if purity_scores else 0.0
    )
    return purity_scores, dominant_contexts, mean_purity


def cluster_embeddings(embeddings, n_clusters, random_state=42):
    embeddings = np.asarray(embeddings)
    if embeddings.ndim > 2:
        embeddings = embeddings.reshape(embeddings.shape[0], -1)

    if embeddings.ndim != 2:
        raise ValueError(f"Expected 2D embeddings after flattening; got {embeddings.shape}")
    if len(embeddings) < 3:
        raise ValueError("At least three trajectories are required for clustering.")
    if not 2 <= n_clusters < len(embeddings):
        raise ValueError(
            f"n_clusters must be between 2 and {len(embeddings) - 1}; "
            f"received {n_clusters}."
        )

    model = KMeans(
        n_clusters=n_clusters,
        random_state=random_state,
        n_init=50,
    )
    labels = model.fit_predict(embeddings)

    unique_labels = np.unique(labels)
    metrics = {}
    if 1 < len(unique_labels) < len(embeddings):
        metrics["silhouette"] = float(silhouette_score(embeddings, labels))
        metrics["davies_bouldin"] = float(davies_bouldin_score(embeddings, labels))
        metrics["calinski_harabasz"] = float(
            calinski_harabasz_score(embeddings, labels)
        )

    return embeddings, labels, metrics


def save_tsne_plot(embeddings, labels, output_path, title, random_state=42):
    perplexity = min(30, max(1, len(embeddings) - 1))
    reducer = TSNE(
        n_components=2,
        random_state=random_state,
        init="pca",
        learning_rate="auto",
        perplexity=perplexity,
    )
    points_2d = reducer.fit_transform(embeddings)

    plt.figure(figsize=(10, 8))
    scatter = plt.scatter(
        points_2d[:, 0],
        points_2d[:, 1],
        c=labels,
        cmap="viridis",
        s=15,
    )
    plt.title(title)
    plt.xlabel("t-SNE component 1")
    plt.ylabel("t-SNE component 2")
    plt.colorbar(scatter, label="Cluster label")
    plt.grid(True)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    plt.close()


def evaluate(dataset, processed_root, n_clusters=None, embedding_file=None,
             random_state=42, make_tsne=True):
    data = load_evaluation_data(dataset, processed_root, embedding_file)
    n_clusters = n_clusters or DEFAULT_CLUSTERS[dataset]

    embeddings, labels, metrics = cluster_embeddings(
        data["embeddings"],
        n_clusters=n_clusters,
        random_state=random_state,
    )

    purity, dominant_contexts, mean_purity = calculate_context_purity(
        labels,
        data["valid_ids"],
        data["day_hour_pairs"],
        data["weekday_date_indices"],
    )

    output_dir = data["output_dir"]
    evaluation_dir = output_dir / "evaluation"
    evaluation_dir.mkdir(parents=True, exist_ok=True)

    np.save(evaluation_dir / f"cluster_labels_{dataset}.npy", labels)

    results = {
        "dataset": dataset,
        "embedding_file": str(data["embeddings_path"]),
        "n_trajectories": int(len(embeddings)),
        "n_clusters": int(n_clusters),
        "metrics": metrics,
        "cluster_context_purity": purity,
        "dominant_contexts": {
            str(cluster): {
                "weekday_hour": context,
                "count": count,
            }
            for cluster, (context, count) in dominant_contexts.items()
        },
        "mean_context_purity": mean_purity,
    }

    with open(evaluation_dir / f"evaluation_{dataset}.json", "w") as f:
        json.dump(results, f, indent=2)

    if make_tsne:
        save_tsne_plot(
            embeddings,
            labels,
            evaluation_dir / f"tsne_{dataset}.png",
            f"STC-Traj2vec - {dataset.capitalize()} (K={n_clusters})",
            random_state,
        )

    print(f"\nEvaluation: {dataset}")
    print(f"Trajectories: {len(embeddings)}")
    print(f"Clusters: {n_clusters}")
    for name, value in metrics.items():
        print(f"{name}: {value:.4f}")
    print(f"Mean context purity: {mean_purity:.4f}")
    for cluster, (context, count) in dominant_contexts.items():
        print(f"Cluster {cluster}: dominant weekday-hour={context}, count={count}")
    print(f"Results saved to: {evaluation_dir}")


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate trajectory embeddings for Geolife or Porto."
    )
    parser.add_argument(
        "--dataset",
        choices=["geolife", "porto"],
        required=True,
    )
    parser.add_argument("--processed-root", default="./processed")
    parser.add_argument("--clusters", type=int, default=None)
    parser.add_argument("--embedding-file", default=None)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument("--no-tsne", action="store_true")
    args = parser.parse_args()

    evaluate(
        dataset=args.dataset,
        processed_root=args.processed_root,
        n_clusters=args.clusters,
        embedding_file=args.embedding_file,
        random_state=args.random_state,
        make_tsne=not args.no_tsne,
    )


if __name__ == "__main__":
    main()
